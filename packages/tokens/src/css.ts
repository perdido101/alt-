import { guardianDark, guardianLight, type ColorScheme } from './colors';
import { radii, spacing } from './layout';
import { fontFamily } from './type';

const kebab = (s: string) => s.replace(/([a-z0-9])([A-Z])/g, '$1-$2').toLowerCase();

function vars(scheme: ColorScheme, indent: string): string {
  return Object.entries(scheme)
    .map(([k, v]) => `${indent}--color-${kebab(k)}: ${v};`)
    .join('\n');
}

/** Builds tokens.css: light by default, dark via prefers-color-scheme or [data-theme="dark"]. */
export function buildCss(): string {
  const shared = [
    ...Object.entries(radii).map(([k, v]) => `  --radius-${k}: ${v}px;`),
    ...Object.entries(spacing).map(([k, v]) => `  --space-${k}: ${v}px;`),
    `  --font-sans: ${fontFamily.css};`,
  ].join('\n');
  return `/* Generated by packages/tokens/scripts/generate-css.ts. Do not edit by hand. */
:root {
${shared}
${vars(guardianLight, '  ')}
}

@media (prefers-color-scheme: dark) {
  :root:not([data-theme="light"]) {
${vars(guardianDark, '    ')}
  }
}

:root[data-theme="dark"] {
${vars(guardianDark, '  ')}
}
`;
}
